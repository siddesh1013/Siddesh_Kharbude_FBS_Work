### Also Called Relational Operator
#1. == Exact Equals to
print(x == 10)
print(x == '10')

#2. != Not Equals to
print(x != '10')

#3. >
print(y > x)

#4. <
print(y < x)

#5. >= # Greater than Equal to
print(x >= 10)

#6. <= # Less than Equal to
print(x <= 20)


