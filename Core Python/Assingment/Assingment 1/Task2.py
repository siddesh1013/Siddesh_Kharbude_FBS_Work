### Write a program to calculate area of rectangle based on length and breadth.

#Take Input
length = int(input('Enter length of rectangle:(in cm)'))
breadth = int(input('Enter breadth of rectangle:(in cm)'))

#Perform Further Calculation
area = length * breadth

#Display Result
print(f'Area of rectangle with length {length} and breadth {breadth} is {area} sq.cm.')